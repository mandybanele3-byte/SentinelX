function renderHistory() {
  const historyRows = id("historyRows");
  if (!historyRows) return;

  historyRows.innerHTML = history
    .map(
      item => `
        <tr>
          <td>${escapeHtml(item.id)}</td>
          <td>${escapeHtml(item.type)}</td>
          <td>${escapeHtml(item.sender)}</td>
          <td>${escapeHtml(item.date)}</td>
          <td>${item.score}/100</td>
          <td>
            <span class="badge ${levelClass(item.level)}">
              ${escapeHtml(item.level)}
            </span>
          </td>
        </tr>
      `
    )
    .join("");

  const high = history.filter(item => item.score >= 70).length;
  const safe = history.filter(item => item.score < 30).length;

  const average =
    history.length > 0
      ? Math.round(
          history.reduce((sum, item) => sum + item.score, 0) /
            history.length
        )
      : 0;

  [["totalScans", history.length],["highCount", high],["safeCount", safe],["avgScore", average]].forEach(
    ([idName, value]) => text(idName, value)
  );
}

